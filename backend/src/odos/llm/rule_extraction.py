"""LLM rule extraction: Custom Legal JSON 2.0 (`document.json`) -> Amazon Bedrock -> Rule JSON 2.0 (`rules.json`).

The model receives the Legal JSON itself, unchanged (the whole document, or the selected provisions with their ancestors:
`element_ids`). There is no chunking, filtering or token optimisation: a request that does not fit the model's context
window, and an answer that is cut off, are reported as errors, never truncated silently.

The model's answer is only a proposal. Every record is checked and its provenance is rewritten from the Legal JSON before
it is accepted, so the model cannot invent a source:

* `schemaVersion` is `2.0`, `review.status` is always `draft` (a person reviews it);
* `source.documentId`, `documentTitle` and `language` come from the Legal JSON;
* every `source.elements[].elementId` must be an element ID of the text the model was given, otherwise the record is
  rejected; `pdfPages` are copied from that element; a `sentenceId` is kept only if the Legal JSON has that sentence on
  that element;
* a `references[].elementId` that does not exist in the document is removed and the reference becomes `unresolved`;
* unambiguous form errors are repaired along the schema (`odos.llm.rule_repair`; each repair is flagged);
* the quality checks of `odos.llm.rule_checks` run (fact identifiers and their translation, self-references, units,
  split bounds, periods written as numbers, alternatives that change the operator, numbers as strings; across records:
  duplicates, repeated exceptions, contradictory operators, inconsistent value types, units, fact spellings and actor
  names);
* the record must validate against `backend/schemas/rule-json/rule.schema.json`, the one Rule JSON schema;
* `odos.llm.source_checks` compares the accepted records with the cited text (thresholds, fractions, periods and dates
  that are not in the machine-readable logic are flagged) and reports uncited sentences and elements
  (`_generation.coverage`).

The instructions sent to the model are layered (general / language / document type) in `odos.llm.profiles`.

Rejected records are listed with their reasons and the record as proposed (`candidate`) in `rules.json` under
`_generation.rulesRejected`; they are not part of `rules`.
"""


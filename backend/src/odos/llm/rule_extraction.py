SYSTEM_PROMPT = """You are a legal-engineering assistant. You turn a normative document, given as ODOS Custom Legal JSON 2.0, into Rule JSON 2.0 records.

INPUT. A JSON object with the document metadata and `structure`, a tree of nodes. This is the reduced/applicability-filtered LLM input V2, not the full original. A node has `id` (stable element ID), `type`, `number`, `title`, `text`, `pages` and `children` where applicable. Redundant native-language type labels and printed node markers are omitted. Derive citation labels from the document type, node type, number and ancestor hierarchy; never change or invent an element ID. `text` is the node's OWN text only; the text of its children is in the children, so read the tree in order. `sentences` give sentence IDs and the element ranges they span.

TASK. Extract every operative requirement, prohibition, permission, definition and procedural requirement as Rule JSON records.

OUTPUT. Reply with ONE JSON object and nothing else, no prose and no code fences: {"rules": [ ... ]}. Use {"rules": []} if the text contains no rule. Every record must validate against this JSON Schema (Draft 2020-12; each record is a `Rule`):

<schema>
__SCHEMA__
</schema>

RULES.
__INSTRUCTIONS__

EXAMPLE of a valid record (illustrative and document-neutral, not from the input):
__EXAMPLE__"""


def build_system_prompt(legal_json: dict | None = None) -> str:
    """The system prompt: general instructions plus the language glossary and document-type profile of `legal_json`."""
    instructions, _ = instructions_for(legal_json or {})
    schema = json.dumps(rule_schema(), ensure_ascii=False, separators=(",", ":"))
    example = json.dumps(EXAMPLE_RULE, ensure_ascii=False, separators=(",", ":"))
    return SYSTEM_PROMPT.replace("__SCHEMA__", schema).replace("__INSTRUCTIONS__", instructions).replace("__EXAMPLE__", example)


def estimate_tokens(text: str) -> int:
    """A cautious upper estimate; the real count is `usage.inputTokens` of the response."""
    return math.ceil(len(text) / CHARS_PER_TOKEN)


# ── scope ─────────────────────────────────────────────────────────────────────────────────────────────────────────────

# the document-level fields kept when only selected provisions are sent (front matter and table of contents are left out)
METADATA_KEYS = ("schemaVersion", "id", "title", "shortTitle", "documentType", "nativeDocumentType", "legalSystem", "language",
                 "version", "publicationDate", "adoptionDate", "subject", "identifiers", "pageCount")


def _walk(nodes: list[dict]):
    for node in nodes:
        yield node
        yield from _walk(node.get("children", []))


def _prune(node: dict, selected: set[str], inside: bool = False) -> dict | None:
    """The selected subtrees with their ancestors; ancestors keep their own fields but only the children on the path."""
    inside = inside or node["id"] in selected
    kept = [k for child in node.get("children", []) if (k := _prune(child, selected, inside))]
    if not inside and not kept:
        return None
    out = {k: v for k, v in node.items() if k != "children"}
    if kept:
        out["children"] = kept
    return out


def scope_document(legal_json: dict, element_ids: list[str]) -> dict:
    """The Legal JSON reduced to the given elements (each with its whole subtree) and their ancestors. Structure, IDs and
    page numbers of the kept nodes are unchanged; sentences and footnotes are kept where they belong to kept nodes."""
    structure = legal_json.get("structure") or []
    known = {n["id"] for n in _walk(structure)}
    unknown = [i for i in element_ids if i not in known]
    if unknown:
        raise InvalidScopeError(f"Not an element ID of this document: {', '.join(unknown)}")
    pruned = [p for top in structure if (p := _prune(top, set(element_ids)))]
    kept = {n["id"] for n in _walk(pruned)}
    scoped = {k: legal_json[k] for k in METADATA_KEYS if k in legal_json}
    scoped["structure"] = pruned
    scoped["sentences"] = [s for s in legal_json.get("sentences", []) if s.get("ranges") and all(r["elementId"] in kept for r in s["ranges"])]
    scoped["footnotes"] = [f for f in legal_json.get("footnotes", []) if any(a in kept for a in f.get("anchorElementIds", []))]
    return scoped


@dataclass
class PreparedRequest:
    system: str
    user: str
    scope: str | list[str]  # "document" or the requested element IDs
    document: dict  # what the model is given
    estimated_input_tokens: int
    max_output_tokens: int
    context_tokens: int

    @property
    def fits(self) -> bool:
        return self.estimated_input_tokens + self.max_output_tokens <= self.context_tokens


def prepare_request(legal_json: dict, config: BedrockConfig, element_ids: list[str] | None = None) -> PreparedRequest:
    """Build the prompt and estimate its size. Raises `DocumentTooLargeError` if it cannot fit the context window."""
    if not legal_json.get("structure"):
        raise InvalidScopeError("The Legal JSON has no structure to extract rules from.")
    from odos.llm_input.artifacts import build_inputs
    _, effective, _ = build_inputs(legal_json)
    if not effective.get("structure"):
        raise InvalidScopeError("No provisions remain after LLM input reduction and applicability filtering.")
    document = scope_document(effective, element_ids) if element_ids else effective
    body = json.dumps(document, ensure_ascii=False, separators=(",", ":"))
    scope: str | list[str] = list(element_ids) if element_ids else "document"
    where = "the applicability-filtered document (LLM input V2)" if scope == "document" else "the provisions " + ", ".join(element_ids or [])
    user = f"Legal JSON 2.0 of {where}:\n<legal_json>\n{body}\n</legal_json>\n\nExtract the Rule JSON records now."
    system = build_system_prompt(legal_json)
    request = PreparedRequest(system=system, user=user, scope=scope, document=document,
                              estimated_input_tokens=estimate_tokens(system) + estimate_tokens(user),
                              max_output_tokens=config.max_tokens, context_tokens=config.context_tokens)
    if not request.fits:
        hint = "" if scope != "document" else " Select provisions with element_ids (--element-id) to extract part of the document."
        raise DocumentTooLargeError(
            f"The request needs about {request.estimated_input_tokens:,} input tokens plus up to {request.max_output_tokens:,} "
            f"output tokens, more than the {request.context_tokens:,}-token context window. Nothing was sent or truncated.{hint}")
    return request



@dataclass
class ExtractionResult:
    rules: list[dict]
    rejected: list[dict] = field(default_factory=list)  # {"index", "id", "reasons", "candidate": the record as proposed}
    generation: dict = field(default_factory=dict)

    def to_json_dict(self) -> dict:
        """The content of `rules.json`: the `{ "rules": [...] }` collection the viewer reads, plus `_generation`."""
        return {"_generation": {**self.generation, "rulesRejected": self.rejected}, "rules": self.rules}


CORRECTION_PROMPT = ("Your answer could not be parsed as JSON ({error}). Reply again with the COMPLETE answer as ONE valid "
                     'JSON object {{"rules": [...]}} and nothing else: no prose, no code fences, no comments. Escape every '
                     'double quote inside a string as \\".')


@dataclass
class _ModelAnswer:
    parsed: ParsedOutput
    responses: list[BedrockResponse]
    diagnostics: list[str]
    partial: bool = False


def _ask_model(client: BedrockClient, request: PreparedRequest, *, diagnostics_dir: Path | None, accept_partial: bool,
               document_id: str) -> _ModelAnswer:
    """The model's answer, parsed; at most `client.config.output_retries` (0 or 1) correction requests when the answer is
    not valid JSON. Every unusable answer is kept as a diagnostic when `diagnostics_dir` is given."""
    responses: list[BedrockResponse] = []
    diagnostics: list[str] = []
    history: list[tuple[str, str]] = []
    user = request.user
    retries = min(client.config.output_retries, 1)
    while True:
        response = client.converse(request.system, user, history=history or None)
        responses.append(response)
        attempt = len(responses)

        def keep(error: str) -> None:
            if diagnostics_dir is not None:
                metadata = {"attempt": attempt, "modelId": client.config.model_id, "stopReason": response.stop_reason,
                            "inputTokens": response.input_tokens, "outputTokens": response.output_tokens,
                            "documentId": document_id, "scope": request.scope}
                try:
                    diagnostics.append(save_diagnostic(diagnostics_dir, text=response.text, error=error, metadata=metadata,
                                                       secrets=(os.environ.get(API_KEY_ENV, ""),)))
                except OSError:
                    log.exception("could not save the diagnostic of an unusable model answer")

        if response.truncated:  # a retry would be cut off at the same limit
            keep("output token limit reached")
            raise OutputTruncatedError(
                f"The answer reached the output limit of {request.max_output_tokens:,} tokens and is incomplete; nothing was "
                "used. Select fewer provisions (element_ids / --element-id) or raise ODOS_BEDROCK_MAX_TOKENS (model maximum: 64,000).")
        try:
            if response.stop_reason == "malformed_model_output":
                raise OutputParseError("Bedrock reported malformed model output")
            return _ModelAnswer(parse_model_output(response.text), responses, diagnostics)
        except OutputParseError as e:
            keep(str(e))
            if attempt <= retries:
                log.warning("model answer %d is not valid JSON (%s); one correction request follows", attempt, e)
                history = [("user", request.user), ("assistant", response.text)]
                user = CORRECTION_PROMPT.format(error=e)
                continue
            if accept_partial and e.salvaged:
                log.warning("model answer is not valid JSON (%s); %d complete records before the defect are used", e, len(e.salvaged))
                return _ModelAnswer(ParsedOutput(e.salvaged, "partial", notes=[f"answer cut at the JSON defect: {e}"]),
                                    responses, diagnostics, partial=True)
            where = f" Kept for diagnosis as {', '.join(diagnostics)}." if diagnostics else ""
            raise MalformedOutputError(
                f"The model's answer is not valid JSON ({e}) after {attempt} request(s); nothing was used.{where}",
                diagnostics) from None


def extract_rules(legal_json: dict, *, client: BedrockClient | None = None, element_ids: list[str] | None = None,
                  diagnostics_dir: Path | None = None, accept_partial: bool = False) -> ExtractionResult:
    """Send the Legal JSON (or the selected provisions) to Bedrock and return the validated Rule JSON records.

    An answer that is not valid JSON is kept in `diagnostics_dir` (if given) and asked for once more if
    `ODOS_BEDROCK_OUTPUT_RETRIES` allows (0 or 1; never more). With `accept_partial`, the complete records before a
    defect of the last answer are used (and the result is marked partial); by default such an answer is rejected.

    Raises `DocumentTooLargeError` before anything is sent, `OutputTruncatedError` / `MalformedOutputError` for an unusable
    answer, and `odos.llm.bedrock.BedrockError` subclasses for API failures."""
    client = client or BedrockClient()
    request = prepare_request(legal_json, client.config, element_ids)
    ctx = _context(legal_json, request.document)
    answer = _ask_model(client, request, diagnostics_dir=diagnostics_dir, accept_partial=accept_partial,
                        document_id=ctx.document_id)
    raw_rules = answer.parsed.rules
    response = answer.responses[-1]

    generated_by = f"Model: {client.config.model_id} (Amazon Bedrock, {client.config.region})"
    taken: set[str] = set()
    report: dict = {}
    rules, rejected = [], []
    index_of: dict[str, int] = {}
    for index, raw in enumerate(raw_rules):
        rule, reasons = finalize_rule(raw, ctx, taken, generated_by, report)
        if rule is not None:
            rules.append(rule)
            index_of[rule["id"]] = index
        else:  # kept as proposed, so a reviewer can still use a rule that failed on form
            rejected.append({"index": index, "id": raw.get("id") if isinstance(raw, dict) else None, "reasons": reasons,
                             "candidate": raw})
    rules, duplicates, set_flags = check_rule_set(rules)
    for rule, reason in duplicates:
        rejected.append({"index": index_of[rule["id"]], "id": rule["id"], "reasons": [reason],
                         "candidate": raw_rules[index_of[rule["id"]]]})
    source = SourceText.of(request.document, element_ids)
    text_flags = check_quantities(rules, source)
    for rule in rules:
        add_flags(rule, set_flags.get(rule["id"], []) + text_flags.get(rule["id"], []))
    rejected.sort(key=lambda r: r["index"])
    report_coverage = coverage(rules, source, [r["candidate"] for r in rejected])
    if rejected:  # IDs and indexes only: reasons and candidates may quote the document
        log.warning("%d of %d rules rejected: %s", len(rejected), len(raw_rules),
                    ", ".join(f"#{r['index']} {r['id']!r}" for r in rejected if isinstance(r["id"], (str, type(None)))))
    flagged = sum(any(a.startswith(FLAG_PREFIX) for a in r["review"].get("ambiguities", [])) for r in rules)
    repairs = report.get("schemaRepairs", [])
    generation = {
        "provider": "aws-bedrock", "modelId": client.config.model_id, "region": client.config.region,
        "inputView": "llm_applicability_input_v2.json",
        "generatedAt": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "documentId": ctx.document_id, "scope": request.scope, "stopReason": response.stop_reason,
        "inputTokens": sum(r.input_tokens for r in answer.responses),
        "outputTokens": sum(r.output_tokens for r in answer.responses), "rulesProposed": len(raw_rules),
        "profile": profile_for(legal_json).name, "promptVersion": PROMPT_VERSION,
        "rulesFlagged": flagged,
        "counts": {"proposed": len(raw_rules), "accepted": len(rules), "rejected": len(rejected), "repaired": len(repairs),
                   "flagged": flagged},
        "modelOutput": {"requests": len(answer.responses), "parse": answer.parsed.mode, "partial": answer.partial,
                        "ignoredCharacters": answer.parsed.ignored_chars, "notes": answer.parsed.notes,
                        "diagnostics": answer.diagnostics},
        "ruleIdScheme": "<documentId>-<local id>",
        "factRenames": report.get("factRenames", {}), "factTranslations": report.get("factTranslations", {}),
        "selfReferencesRemoved": report.get("selfReferencesRemoved", 0), "schemaRepairs": repairs,
        "coverage": report_coverage,
        "review": {"status": "draft", "humanReviewRequired": True,
                   "reason": "LLM-generated drafts; no record is a legal compliance decision until a person has reviewed it."},
        "note": REVIEW_NOTE,
    }
    return ExtractionResult(rules=rules, rejected=rejected, generation=generation)


def write_rules_json(result: ExtractionResult, path: Path) -> Path:
    """Write `rules.json` atomically (a failed write leaves an existing file untouched)."""
    tmp = path.with_name(f".{path.name}.{os.getpid()}.tmp")
    try:
        tmp.write_text(json.dumps(result.to_json_dict(), indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
        os.replace(tmp, path)
    finally:
        tmp.unlink(missing_ok=True)
    return path

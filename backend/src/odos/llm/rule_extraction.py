SCHEMA_PATH = Path(__file__).resolve().parents[3] / "schemas" / "rule-json" / "rule.schema.json"
CHARS_PER_TOKEN = 3  # deliberately low (German legal text and JSON syntax run at about 3 to 4): the check errs towards "too large"
REVIEW_NOTE = "Generated by an LLM from the Legal JSON; a draft that needs human review."


class RuleExtractionError(Exception):
    """Base class of the errors of rule extraction (errors of Bedrock itself are `odos.llm.bedrock.BedrockError`)."""


class InvalidScopeError(RuleExtractionError):
    """An element ID given for `element_ids` is not in the document, or the Legal JSON has no structure."""


class DocumentTooLargeError(RuleExtractionError):
    """The request would not fit the model's context window. Nothing was sent."""


class OutputTruncatedError(RuleExtractionError):
    """The answer reached the output token limit and is incomplete, so none of it is used."""


class MalformedOutputError(RuleExtractionError):
    """The answer is not the expected JSON (`{"rules": [...]}`), also after the allowed retry. `diagnostic_ids` name
    the preserved answers (see `odos.llm.model_output.save_diagnostic`)."""

    def __init__(self, message: str, diagnostic_ids: list[str] | None = None):
        super().__init__(message)
        self.diagnostic_ids = diagnostic_ids or []


# ── schema ────────────────────────────────────────────────────────────────────────────────────────────────────────────

_schema: dict | None = None
_validator: Draft202012Validator | None = None


def rule_schema() -> dict:
    global _schema
    if _schema is None:
        _schema = json.loads(SCHEMA_PATH.read_text(encoding="utf-8"))
    return _schema


def rule_validator() -> Draft202012Validator:
    global _validator
    if _validator is None:
        _validator = Draft202012Validator(rule_schema(), format_checker=FormatChecker())
    return _validator



@dataclass
class _Context:
    document_id: str
    title: str | None
    language: str | None
    pages: dict[str, list[int]]  # element ID -> pages, for the elements the model was given
    document_ids: set[str]  # every element ID of the whole document
    sentence_elements: dict[str, set[str]]  # sentence ID -> element IDs it spans


def _context(legal_json: dict, given: dict) -> _Context:
    nodes = [*_walk(given.get("structure", [])), *_walk(given.get("frontMatter", []))]
    everything = [*_walk(legal_json.get("structure", [])), *_walk(legal_json.get("frontMatter", []))]
    return _Context(
        document_id=legal_json.get("id", ""),
        title=legal_json.get("title"),
        language=legal_json.get("language"),
        pages={n["id"]: [p for p in n.get("pages", []) if isinstance(p, int) and p >= 1] for n in nodes},
        document_ids={n["id"] for n in everything},
        sentence_elements={s["id"]: {r["elementId"] for r in s.get("ranges", [])} for s in given.get("sentences", []) if "id" in s},
    )


def finalize_rule(raw: Any, ctx: _Context, taken_ids: set[str], generated_by: str,
                  report: dict | None = None) -> tuple[dict | None, list[str]]:
    """The rule with its provenance rewritten from the Legal JSON and the quality checks of `rule_checks` applied, or
    None with the reasons it is rejected. `report` collects fact renames and removed self-references."""
    if not isinstance(raw, dict):
        return None, ["the record is not a JSON object"]
    rule = copy.deepcopy(raw)
    reasons: list[str] = []
    rule["schemaVersion"] = "2.0"

    source = rule.get("source")
    if not isinstance(source, dict) or not isinstance(source.get("elements"), list) or not source["elements"]:
        return None, ["source.elements is missing or empty"]
    source["documentId"] = ctx.document_id
    for key, value in (("documentTitle", ctx.title), ("language", ctx.language)):
        if value:
            source[key] = value
        else:
            source.pop(key, None)
    elements = []
    for element in source["elements"]:
        element_id = element.get("elementId") if isinstance(element, dict) else None
        if not isinstance(element_id, str) or element_id not in ctx.pages:
            reasons.append(f"source element {element_id!r} is not an element of the supplied text")
            continue
        element = dict(element)
        if ctx.pages[element_id]:
            element["pdfPages"] = ctx.pages[element_id]
        else:
            element.pop("pdfPages", None)
        sentence_id = element.get("sentenceId")
        if sentence_id is not None and not (isinstance(sentence_id, str) and element_id in ctx.sentence_elements.get(sentence_id, ())):
            element.pop("sentenceId")  # not invented: the Legal JSON has no such sentence on this element
        elements.append(element)
    if reasons:
        return None, reasons
    source["elements"] = elements

    exceptions = rule.get("exceptions") if isinstance(rule.get("exceptions"), list) else []
    for references in [rule.get("references"), *[e.get("references") for e in exceptions if isinstance(e, dict)]]:
        for ref in references if isinstance(references, list) else []:
            if isinstance(ref, dict) and ref.get("elementId") is not None and not (
                    isinstance(ref["elementId"], str) and ref["elementId"] in ctx.document_ids):
                del ref["elementId"]
                ref["resolution"] = "unresolved"

    repairs = repair_rule(rule, rule_schema())  # only unambiguous form repairs; see odos.llm.rule_repair
    check = check_rule(rule, ctx.language)  # normalizes/translates fact identifiers, removes self-references, flags problems
    if check.errors:
        return None, check.errors

    review = rule.get("review") if isinstance(rule.get("review"), dict) else {}
    notes = review.get("notes") if isinstance(review.get("notes"), list) else []
    review["status"] = "draft"
    review["notes"] = [*notes, generated_by, REVIEW_NOTE] if generated_by not in notes else notes
    rule["review"] = review
    add_flags(rule, [f"schema repair: {r}" for r in repairs] + check.flags)

    rule_id = scoped_rule_id(ctx.document_id, rule.get("id"))
    candidate, n = rule_id, 1
    while candidate in taken_ids:
        n += 1
        candidate = f"{rule_id}-{n}"
    rule["id"] = candidate

    errors = sorted(rule_validator().iter_errors(rule), key=lambda e: list(e.absolute_path))
    if errors:
        return None, [describe_schema_error(e) for e in errors[:5]]
    taken_ids.add(candidate)
    if report is not None:  # only what was done to accepted records
        report.setdefault("factRenames", {}).update(check.renamed)
        report.setdefault("factTranslations", {}).update(check.translated)
        report["selfReferencesRemoved"] = report.get("selfReferencesRemoved", 0) + check.self_references_removed
        if repairs:
            report.setdefault("schemaRepairs", []).append({"id": candidate, "repairs": [str(r) for r in repairs]})
    return rule, []


_ID_CHARS = re.compile(r"[^a-z0-9._-]+")


def _slug(text: str) -> str:
    return _ID_CHARS.sub("-", text.strip().lower()).strip("-.")


def scoped_rule_id(document_id: str, proposed: Any) -> str:
    """A rule ID that is unique across documents: `<document id>-<local id>`. The document's own `id` (Legal JSON) is the
    prefix, so two documents never share a rule ID, and the same document keeps the same IDs in every run. A proposed ID
    that already starts with the document ID is kept (normalized to lower-case ASCII); `source.documentId` stays the
    authoritative link to the document."""
    document = _slug(document_id) or "document"
    local = _slug(proposed) if isinstance(proposed, str) else ""
    if local == document or local.startswith(f"{document}-"):
        return local
    return f"{document}-{local or 'rule'}"


_NAME = re.compile(r"^[A-Za-z0-9_.-]{1,60}$")


def _compact(value: Any, limit: int = 160) -> str:
    text = json.dumps(value, ensure_ascii=False, separators=(",", ":"))
    return text if len(text) <= limit else text[: limit - 1] + "…"


def describe_schema_error(error: ValidationError) -> str:
    """The most specific reason (for a `oneOf` failure the closest branch), as `path: what is wrong`. The text comes from
    the schema (keyword, expected type, allowed values, required or forbidden property names), never from the record:
    jsonschema's own messages quote the offending value or even the whole record, which is document text, and were cut off
    at 300 characters before the actual defect. Property names of the record are shown only if they are plain identifiers."""
    while error.context:
        error = best_match(error.context)
    where = "/".join(str(p) for p in error.absolute_path) or "(record)"
    rule, expected, instance = error.validator, error.validator_value, error.instance
    if rule == "required":
        what = "missing required property " + ", ".join(repr(k) for k in expected if not isinstance(instance, dict) or k not in instance)
    elif rule == "additionalProperties" and isinstance(instance, dict) and isinstance(error.schema, dict):
        known = set(error.schema.get("properties", {}))
        extra = sorted(k for k in instance if k not in known)
        what = "unexpected property " + ", ".join(repr(k) if isinstance(k, str) and _NAME.match(k) else "<name omitted>" for k in extra)
    elif rule == "enum":
        what = f"not one of {_compact(expected)}"
    elif rule == "const":
        what = f"must be {_compact(expected)}"
    elif rule == "type":
        what = f"expected type {_compact(expected)}"
    elif rule == "not" and isinstance(expected, dict) and set(expected) == {"required"}:
        what = ("property " + ", ".join(repr(k) for k in expected["required"])
                + " is not allowed here: it is mutually exclusive with another property of the record that is also present")
    elif rule == "not":
        what = f"must not match {_compact(expected)}"
    else:
        what = f"fails the schema keyword '{rule}' ({_compact(expected)})"
    return f"{where}: {what}"[:400]


